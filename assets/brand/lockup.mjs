// lockup.mjs — the wordmark, from the kit's geometry.
// -----------------------------------------------------------------------------
// The kit draws every piece of the logo in assets/brand/src/geometry.js from
// a handful of constants and the letter outlines in src/paths.json. This
// script runs that code and writes two things from it:
//
//   assets/brand/svg/wordmark*.svg   the plain wordmark, on dark and on light,
//                                    which the kit does not ship as a file
//   book/theme/metrale.js            the book's menu-bar wordmark, the on-dark
//                                    master inlined so the page makes no extra
//                                    request for it (the book is always dark)
//
// The Docs workflow runs it with --check and fails when a file on disk is not
// what the geometry says. Run it again after the kit changes:
//
//   node assets/brand/lockup.mjs
// =============================================================================

import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(here, '..', '..');
const BRAND = here;
const CHECK = process.argv.includes('--check');

const require = createRequire(import.meta.url);
const G = require(join(BRAND, 'src', 'geometry.js'));
G.setPaths(JSON.parse(readFileSync(join(BRAND, 'src', 'paths.json'), 'utf8')));

const files = {
  [join(BRAND, 'svg', 'wordmark-ondark.svg')]: G.tight(G.wordmark({ theme: 'dark', id: 'w' }), 'Metrale') + '\n',
  [join(BRAND, 'svg', 'wordmark.svg')]: G.tight(G.wordmark({ theme: 'light', id: 'w' }), 'Metrale') + '\n',
  [join(BRAND, 'svg', 'wordmark-mono-ondark.svg')]: G.tight(G.wordmark({ theme: 'dark', id: 'w', mono: true }), 'Metrale') + '\n',
  [join(BRAND, 'svg', 'wordmark-mono.svg')]: G.tight(G.wordmark({ theme: 'light', id: 'w', mono: true }), 'Metrale') + '\n',
};

// The book (mdBook) has no bundler, so its menu-bar script carries the
// wordmark inline. It replaces the title mdBook sets in type with the wordmark,
// linked to the book's front page, and "Engine docs" beside it; the link's name
// keeps the title for assistive technology. book/theme/css/wordmark.css places it.
const bookWordmark = files[join(BRAND, 'svg', 'wordmark-ondark.svg')].trim();
files[join(REPO, 'book', 'theme', 'metrale.js')] = `// Generated by assets/brand/lockup.mjs from assets/brand/svg/wordmark-ondark.svg. Do not edit.
// The Metrale wordmark in the book's menu bar, with "Engine docs" beside it.
(function () {
  var wordmark = ${JSON.stringify(bookWordmark)};
  function place() {
    var h = document.querySelector('h1.menu-title');
    if (!h || h.querySelector('.metrale-lockup')) return;
    var root = typeof window.path_to_root === 'string' ? window.path_to_root : '';
    h.innerHTML =
      '<a class="metrale-lockup" href="' +
      root +
      'index.html" aria-label="The Metrale Engine Book, front page">' +
      wordmark +
      '</a><span class="metrale-docs" aria-hidden="true">Engine docs</span>';
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', place);
  else place();
})();
`;

let stale = 0;
for (const [file, content] of Object.entries(files)) {
  let current;
  try {
    current = readFileSync(file, 'utf8');
  } catch {
    current = null;
  }
  if (current === content) continue;
  stale++;
  if (!CHECK) writeFileSync(file, content);
}
if (CHECK) {
  if (stale) {
    console.error(`lockup: ${stale} generated file(s) are behind assets/brand/src. Run node assets/brand/lockup.mjs`);
    process.exit(1);
  }
  console.log('lockup: current');
} else {
  console.log(`lockup: wrote ${stale} file(s)`);
}
