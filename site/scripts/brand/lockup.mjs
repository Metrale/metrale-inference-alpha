// =============================================================================
// lockup.mjs — the brand artwork, from the kit's geometry, for the two sites.
// -----------------------------------------------------------------------------
// The kit draws every piece of the logo in assets/brand/src/geometry.js from
// a handful of constants and the letter outlines in src/paths.json. This
// script runs that code and writes two things from it:
//
//   web-shared/brand-art.js          the paths and boxes the lockup component
//                                    draws with (MetraleLockup.svelte), so the
//                                    site never holds a redrawn copy
//   assets/brand/svg/wordmark*.svg   the plain wordmark, on dark and on light,
//                                    which the kit does not ship as a file
//   book/theme/metrale.js            the book's menu-bar wordmark, the on-dark
//                                    master inlined so the page makes no extra
//                                    request for it (the book is always dark)
//
// src/lib/lockup-artwork.test.js runs it with --check and fails when the module
// on disk is not what the geometry says. Run it again after the kit changes:
//
//   node scripts/brand/lockup.mjs
// =============================================================================

import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(here, '..', '..', '..');
const BRAND = join(REPO, 'assets', 'brand');
const OUT = join(REPO, 'web-shared', 'brand-art.js');
const CHECK = process.argv.includes('--check');

const require = createRequire(import.meta.url);
const G = require(join(BRAND, 'src', 'geometry.js'));
G.setPaths(JSON.parse(readFileSync(join(BRAND, 'src', 'paths.json'), 'utf8')));

// The pieces of a body, in drawing order, each with which ink it takes.
const pieces = (body) =>
  [...body.matchAll(/<(path|rect)\b([^>]*?)\/?>/g)].map((m) => {
    const attrs = m[2];
    const fill = attrs.match(/fill="([^"]+)"/)?.[1] ?? '';
    const ink =
      /#\w+w\)|#[0-9A-F]{6}$/i.test(fill) && !/v\)|c\)|g\)/.test(fill)
        ? 'ink'
        : fill.endsWith('v)')
          ? 'violet'
          : fill.endsWith('c)')
            ? 'cyan'
            : fill.endsWith('g)')
              ? 'gold'
              : 'ink';
    if (m[1] === 'rect')
      return {
        kind: 'rect',
        ink,
        x: +attrs.match(/x="([^"]+)"/)[1],
        y: +attrs.match(/y="([^"]+)"/)[1],
        w: +attrs.match(/width="([^"]+)"/)[1],
        h: +attrs.match(/height="([^"]+)"/)[1],
      };
    return {
      kind: 'path',
      ink,
      d: attrs.match(/d="([^"]+)"/)[1],
      stroke: /stroke-width="([^"]+)"/.test(attrs) ? +attrs.match(/stroke-width="([^"]+)"/)[1] : 0,
    };
  });

const word = G.wordmark({ theme: 'dark', id: 'w' });
const mark = G.mark({ theme: 'dark', id: 'i' });
const compact = G.markCompact({ theme: 'dark', id: 'i' });
const box = (a) => ({ x0: a.x0, y0: a.y0, width: a.width, height: a.height });

const art = {
  generated: 'by site/scripts/brand/lockup.mjs from assets/brand/src/geometry.js. Do not edit.',
  base: G.BASE,
  mWidth: G.M_W,
  wordWidth: G.WORD_W,
  clear: G.CLEAR,
  colors: G.C,
  boxes: { wordmark: box(word), mark: box(mark), compact: box(compact) },
  wordmark: pieces(word.body),
  mark: pieces(mark.body),
  compact: pieces(compact.body),
};
const module_ = `// Generated ${art.generated}\n// The brand artwork as data: what MetraleLockup.svelte draws. Colours are the\n// kit's reference values; the component maps each ink to a token.\nexport const ART = ${JSON.stringify(art, null, 1)};\n`;

const files = {
  [OUT]: module_,
  [join(BRAND, 'svg', 'wordmark-ondark.svg')]: G.tight(G.wordmark({ theme: 'dark', id: 'w' }), 'Metrale') + '\n',
  [join(BRAND, 'svg', 'wordmark.svg')]: G.tight(G.wordmark({ theme: 'light', id: 'w' }), 'Metrale') + '\n',
  [join(BRAND, 'svg', 'wordmark-mono-ondark.svg')]: G.tight(G.wordmark({ theme: 'dark', id: 'w', mono: true }), 'Metrale') + '\n',
  [join(BRAND, 'svg', 'wordmark-mono.svg')]: G.tight(G.wordmark({ theme: 'light', id: 'w', mono: true }), 'Metrale') + '\n',
};

// The book (mdBook) has no bundler, so its menu-bar script carries the
// wordmark inline. It replaces the title mdBook sets in type with the wordmark,
// linked to the book's front page, and "Engine docs" beside it; the link's name
// keeps the title for assistive technology. book/theme/css/wordmark.css places it.
const bookWordmark = files[join(BRAND, 'svg', 'wordmark-ondark.svg')].trim();
files[join(REPO, 'book', 'theme', 'metrale.js')] = `// Generated by site/scripts/brand/lockup.mjs from assets/brand/svg/wordmark-ondark.svg. Do not edit.
// The Metrale wordmark in the book's menu bar, with "Engine docs" beside it.
(function () {
  var wordmark = ${JSON.stringify(bookWordmark)};
  function place() {
    var h = document.querySelector('h1.menu-title');
    if (!h || h.querySelector('.metrale-lockup')) return;
    var root = typeof window.path_to_root === 'string' ? window.path_to_root : '';
    h.innerHTML =
      '<a class="metrale-lockup" href="' +
      root +
      'index.html" aria-label="The Metrale Engine Book, front page">' +
      wordmark +
      '</a><span class="metrale-docs" aria-hidden="true">Engine docs</span>';
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', place);
  else place();
})();
`;

let stale = 0;
for (const [file, content] of Object.entries(files)) {
  let current;
  try {
    current = readFileSync(file, 'utf8');
  } catch {
    current = null;
  }
  if (current === content) continue;
  stale++;
  if (!CHECK) writeFileSync(file, content);
}
if (CHECK) {
  if (stale) {
    console.error(`lockup: ${stale} generated file(s) are behind assets/brand/src. Run node scripts/brand/lockup.mjs`);
    process.exit(1);
  }
  console.log('lockup: current');
} else {
  console.log(
    `lockup: wrote ${stale} file(s). wordmark ${art.boxes.wordmark.width}x${art.boxes.wordmark.height}, mark ${art.boxes.mark.width}x${art.boxes.mark.height}, ${art.wordmark.length} pieces`
  );
}
